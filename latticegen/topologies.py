"""
Strut skeletons (lattice topologies) in fractional coordinates.

A :class:`Skeleton` is a list of straight struts ``(p, q)`` with fractional
endpoints, plus optional isolated points (spherical nodes).  Struts are
stored once per unit cell (deduplicated modulo lattice translations); the
periodic images are generated by the field builders.

Built-in topologies (all cubic):

    sc        simple cubic          3 struts / cell,  6-connected nodes
    bcc       body-centred cubic    8 struts / cell,  8-connected
    fcc       face-centred cubic   12 struts / cell   (corner -> face centre)
    bccz      bcc + vertical pillars
    fccz      fcc + vertical pillars
    fbcc      fcc + bcc
    octet     octet truss          24 struts / cell  (fcc + octahedral core)
    diamond   diamond cubic        16 struts / cell,  4-connected
    kelvin    Kelvin foam (tetrakaidecahedra), 24 struts / cell

Use ``skeleton("octet")`` or the functions directly, ``Skeleton.custom`` for
your own, and ``+`` to merge two skeletons.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field

import numpy as np


# --------------------------------------------------------------------------- #
# canonical deduplication modulo lattice translations
# --------------------------------------------------------------------------- #

def _canonical_segment(p, q, tol_digits=6):
    """Return (p', q', key): the segment shifted so that its midpoint lies in
    [0,1)^3, with a canonical direction sign, and a hashable key."""
    p, q = np.asarray(p, float), np.asarray(q, float)
    d = q - p
    for comp in d:                        # first non-zero component positive
        if abs(comp) > 1e-9:
            if comp < 0:
                p, q, d = q, p, -d
            break
    m = 0.5 * (p + q)
    shift = np.floor(m + 1e-9)
    p, q = p - shift, q - shift
    key = (tuple(np.round(0.5 * (p + q), tol_digits)), tuple(np.round(d, tol_digits)))
    return p, q, key


def unique_segments(segments):
    """Deduplicate a list of (p, q) fractional segments modulo lattice
    translations and endpoint order."""
    out = {}
    for p, q in segments:
        p, q, key = _canonical_segment(p, q)
        if np.linalg.norm(q - p) < 1e-12:
            continue
        out.setdefault(key, (p, q))
    return list(out.values())


def _wrap_point(x, tol_digits=6):
    x = np.asarray(x, float)
    return tuple(np.round(np.mod(x + 1e-9, 1.0) - 1e-9, tol_digits))


# --------------------------------------------------------------------------- #
# Skeleton
# --------------------------------------------------------------------------- #

@dataclass
class Skeleton:
    """Strut skeleton of one unit cell, in fractional coordinates."""

    name: str
    segments: list = field(default_factory=list)     # list of (p, q), arrays (3,)
    points: list = field(default_factory=list)       # isolated points (spheres)
    fourier_defaults: dict = field(default_factory=dict)   # {'sigma': frac of a, 'gmax': units of 2pi/a}

    def __post_init__(self):
        self.segments = unique_segments(self.segments)
        self.points = [np.asarray(p, float) for p in self.points]

    # -- construction ------------------------------------------------------- #
    @classmethod
    def custom(cls, segments, name="custom", points=(), sigma=0.08, gmax=5.5):
        """Build from a list of fractional (p, q) endpoint pairs.  Struts that
        are lattice translates of each other are merged automatically."""
        return cls(name, [(np.asarray(p, float), np.asarray(q, float)) for p, q in segments],
                   list(points), {"sigma": sigma, "gmax": gmax})

    @classmethod
    def from_nodes_and_bonds(cls, nodes, bond_vectors, name="custom", **kw):
        """Struts from every node to node + bond_vector (fractional)."""
        segs = [(np.asarray(n, float), np.asarray(n, float) + np.asarray(b, float))
                for n in nodes for b in bond_vectors]
        return cls.custom(segs, name=name, **kw)

    def __add__(self, other: "Skeleton") -> "Skeleton":
        fd = dict(self.fourier_defaults)
        for k, v in other.fourier_defaults.items():
            fd[k] = min(fd[k], v) if k == "sigma" and k in fd else max(fd.get(k, v), v)
        return Skeleton(f"{self.name}+{other.name}", self.segments + other.segments,
                        self.points + other.points, fd)

    # -- derived geometry ----------------------------------------------------- #
    @property
    def n_struts(self) -> int:
        return len(self.segments)

    def nodes(self) -> np.ndarray:
        """Unique strut endpoints modulo lattice translations, in [0,1)^3."""
        seen = {}
        for p, q in self.segments:
            for x in (p, q):
                seen.setdefault(_wrap_point(x), np.array(_wrap_point(x)))
        for x in self.points:
            seen.setdefault(_wrap_point(x), np.array(_wrap_point(x)))
        return np.array(list(seen.values())) if seen else np.zeros((0, 3))

    def midpoints(self) -> np.ndarray:
        return np.array([0.5 * (p + q) for p, q in self.segments]) if self.segments else np.zeros((0, 3))

    def connectivity(self) -> int:
        """Number of struts meeting at each node (max over nodes)."""
        count = {}
        for p, q in self.segments:
            for x in (p, q):
                k = _wrap_point(x)
                count[k] = count.get(k, 0) + 1
        return max(count.values()) if count else 0

    def strut_lengths(self, cell=None) -> np.ndarray:
        """Cartesian strut lengths (fractional if no cell is given)."""
        A = np.eye(3) if cell is None else getattr(cell, "A", np.asarray(cell, float))
        return np.array([np.linalg.norm((q - p) @ A) for p, q in self.segments])

    def total_length(self, cell=None) -> float:
        return float(self.strut_lengths(cell).sum())

    def __repr__(self) -> str:
        return (f"Skeleton({self.name}: {self.n_struts} struts, {len(self.nodes())} nodes, "
                f"connectivity {self.connectivity()})")


# --------------------------------------------------------------------------- #
# built-in topologies
# --------------------------------------------------------------------------- #

_FCC_BASIS = np.array([[0, 0, 0], [.5, .5, 0], [.5, 0, .5], [0, .5, .5]], float)


def sc() -> Skeleton:
    """Simple cubic: struts along the three cell edges."""
    z = np.zeros(3)
    return Skeleton("sc", [(z, np.array([1., 0, 0])), (z, np.array([0, 1., 0])), (z, np.array([0, 0, 1.]))],
                    fourier_defaults={"sigma": 0.12, "gmax": 4.5})


def bcc() -> Skeleton:
    """Body-centred cubic: 8 half-diagonals from the corners to the body centre."""
    ctr = np.array([.5, .5, .5])
    return Skeleton("bcc", [(np.array(p, float), ctr) for p in itertools.product((0, 1), repeat=3)],
                    fourier_defaults={"sigma": 0.10, "gmax": 4.5})


def fcc() -> Skeleton:
    """Face-centred cubic: struts from each corner to the centres of the three
    adjacent faces (12 unique struts per cell)."""
    segs = []
    for fcentre in _FCC_BASIS[1:]:
        # the four corners of that face
        free = np.where(fcentre == 0)[0][0]
        for s in itertools.product((-.5, .5), repeat=2):
            corner = fcentre.copy()
            idx = [i for i in range(3) if i != free]
            corner[idx[0]] += s[0]
            corner[idx[1]] += s[1]
            segs.append((corner, fcentre))
    return Skeleton("fcc", segs, fourier_defaults={"sigma": 0.07, "gmax": 6.0})


def _pillars(name) -> Skeleton:
    return Skeleton(name, [(np.zeros(3), np.array([0, 0, 1.]))])


def bccz() -> Skeleton:
    """BCC with vertical pillars along the cell edges (bcc + z struts)."""
    s = bcc() + _pillars("z")
    s.name = "bccz"
    return s


def fccz() -> Skeleton:
    """FCC with vertical pillars along the cell edges."""
    s = fcc() + _pillars("z")
    s.name = "fccz"
    return s


def fbcc() -> Skeleton:
    """FCC + BCC combined (20 struts per cell)."""
    s = fcc() + bcc()
    s.name = "fbcc"
    s.fourier_defaults = {"sigma": 0.07, "gmax": 6.0}
    return s


def octet() -> Skeleton:
    """Octet truss: FCC nodes with struts along all <110> nearest-neighbour
    bonds (fcc struts + octahedral core), 24 unique struts per cell."""
    nodes = np.array([b + np.array(o) for b in _FCC_BASIS
                      for o in itertools.product((-1, 0, 1), repeat=3)])
    d_nn = np.sqrt(0.5)
    segs = []
    for i in range(len(nodes)):
        for j in range(i + 1, len(nodes)):
            if abs(np.linalg.norm(nodes[i] - nodes[j]) - d_nn) < 1e-9:
                segs.append((nodes[i], nodes[j]))
    s = Skeleton("octet", segs, fourier_defaults={"sigma": 0.06, "gmax": 6.5})
    assert s.n_struts == 24
    return s


def diamond() -> Skeleton:
    """Diamond cubic: tetrahedral bonds between the two FCC sublattices
    (16 struts per cell, 4-connected)."""
    bonds = np.array([[.25, .25, .25], [.25, -.25, -.25],
                      [-.25, .25, -.25], [-.25, -.25, .25]])
    segs = [(p, p + b) for p in _FCC_BASIS for b in bonds]
    return Skeleton("diamond", segs, fourier_defaults={"sigma": 0.08, "gmax": 5.5})


def kelvin() -> Skeleton:
    """Kelvin cell: BCC tiling of truncated octahedra (tetrakaidecahedra),
    24 struts per cell, 4-connected nodes.  Vertices are the permutations
    of (0, +-1/4, +-1/2) around each polyhedron centre."""
    verts = []
    for perm in itertools.permutations(range(3)):
        for s1, s2 in itertools.product((-1, 1), repeat=2):
            v = np.zeros(3)
            v[perm[1]] = s1 * 0.25
            v[perm[2]] = s2 * 0.5
            verts.append(v)
    verts = np.unique(np.round(np.array(verts), 9), axis=0)      # 24 vertices
    edge_len = np.sqrt(2) / 4
    segs = []
    for centre in (np.zeros(3), np.full(3, 0.5)):
        V = verts + centre
        for i in range(len(V)):
            for j in range(i + 1, len(V)):
                if abs(np.linalg.norm(V[i] - V[j]) - edge_len) < 1e-9:
                    segs.append((V[i], V[j]))
    s = Skeleton("kelvin", segs, fourier_defaults={"sigma": 0.07, "gmax": 5.5})
    assert s.n_struts == 24, s.n_struts
    return s


TOPOLOGIES = {
    "sc": sc, "bcc": bcc, "fcc": fcc, "bccz": bccz, "fccz": fccz,
    "fbcc": fbcc, "octet": octet, "diamond": diamond, "kelvin": kelvin,
}


def skeleton(name: str) -> Skeleton:
    """Look up a built-in topology by name (case-insensitive)."""
    key = name.lower().replace("-", "").replace("_", "")
    if key not in TOPOLOGIES:
        raise KeyError(f"unknown topology {name!r}; available: {', '.join(TOPOLOGIES)}")
    return TOPOLOGIES[key]()


def available() -> list:
    return list(TOPOLOGIES)
